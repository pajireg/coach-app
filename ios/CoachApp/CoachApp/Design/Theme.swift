}

// MARK: - Typography

extension Font {
    static func rcTitle(_ size: CGFloat = 34) -> Font {
        .custom("PretendardVariable", size: size).weight(.bold)
    }

    static func rcHeadline(_ size: CGFloat = 17) -> Font {
        .custom("PretendardVariable", size: size).weight(.semibold)
    }

    static func rcBody(_ size: CGFloat = 15) -> Font {
        .custom("PretendardVariable", size: size)
    }

    static func rcCaption(_ size: CGFloat = 12) -> Font {
        .custom("PretendardVariable", size: size)
    }

    static func rcMono(_ size: CGFloat = 15) -> Font {
        .custom("JetBrainsMono[wght]", size: size)
    }
}

