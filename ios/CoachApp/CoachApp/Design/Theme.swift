import SwiftUI

// MARK: - Colors

extension Color {
    // Zone accents
    static let zoneRecovery = Color(hex: "#4A9EDB")
    static let zoneBase = Color(hex: "#3FB87F")
    static let zoneThreshold = Color(hex: "#E8A94C")
    static let zoneInterval = Color(hex: "#E35D5D")
    static let zoneRest = Color(hex: "#8A8F99")
    static let zoneLong = Color(hex: "#8F7BD4")

    // Brand
    static let rcAccent = Color(hex: "#3FB87F")

    init(hex: String) {
        let hex = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
        var int: UInt64 = 0
        Scanner(string: hex).scanHexInt64(&int)
        let r = Double((int >> 16) & 0xFF) / 255
        let g = Double((int >> 8) & 0xFF) / 255
        let b = Double(int & 0xFF) / 255
        self.init(red: r, green: g, blue: b)
    }
}

extension ZoneColor {
    var color: Color {
        switch self {
        case .recovery: .zoneRecovery
        case .base: .zoneBase
        case .threshold: .zoneThreshold
        case .interval: .zoneInterval
        case .rest: .zoneRest
        case .long: .zoneLong
        }
    }

    var label: String {
        switch self {
        case .recovery: "회복"
        case .base: "기본"
        case .threshold: "역치"
        case .interval: "인터벌"
        case .rest: "휴식"
        case .long: "장거리"
        }
    }
}

